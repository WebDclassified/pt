/**
 * Phase 21/§123 — deterministic randomness for cinematic scenes.
 * Visual-regression captures must be reproducible: fixed seed → fixed
 * composition. mulberry32 — small, fast, seedable PRNG.
 */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
